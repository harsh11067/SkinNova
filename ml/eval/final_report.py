"""reports/final_report.md (plan §12 definition of done) assembled from the report JSONs — every number cites its file.
Missing measurements are listed as "not yet measured" instead of being skipped.

  python -m ml.eval.final_report
"""
from __future__ import annotations

import json
from pathlib import Path

from ml.common.paths import REPORTS, git_sha


def load(name: str):
    p = REPORTS / name
    try:
        return json.loads(p.read_text()) if p.exists() and p.stat().st_size else None
    except json.JSONDecodeError:
        return None


def pct(x, d=1):
    return "—" if x is None else f"{100 * x:.{d}f} %"


def ci(m):
    if not isinstance(m, dict):
        return "—"
    lo, hi = m.get("ci95", [None, None])
    return f"{100 * m['value']:.1f} % ({100 * lo:.1f}–{100 * hi:.1f})" if lo is not None else f"{100 * m['value']:.1f} %"


def main():
    L = ["# SkinNova — final report", "", f"git {git_sha()} · generated by `ml/eval/final_report.py` from `reports/*.json`.", ""]
    todo = []

    # ---- CV
    adopt = load("cv_v2_adoption.json")
    tag = "_v2" if adopt and adopt.get("decision") == "ADOPT" else ""
    cv = load(f"cv_metrics{tag}.json") or load("cv_metrics.json")
    L += ["## 1. Image classifier", f"Shipped: {'v2 (with SCIN)' if tag else 'v1'} · source `reports/cv_metrics{tag}.json`", "",
          "| split | n | top-1 | top-3 | macro-F1 |", "|---|---|---|---|---|"]
    for s, m in (cv or {}).get("splits", {}).items():
        L.append(f"| {s} | {m['n']} | {ci(m['top1'])} | {ci(m['top3'])} | {ci(m['macro_f1_present_classes'])} |")
    if adopt:
        L += ["", f"v2 adoption (val only, rule pre-registered): {adopt['decision']} — full val F1 v1 {adopt['full_val_f1']['v1']} vs v2 "
                  f"{adopt['full_val_f1']['v2']}; v1-val images v2 {adopt['v1_val_images_f1']['v2']} (≥ 0.723 required)."]
    par = load("cv_parity.json")
    L += ["", f"C3 .tflite parity: max |Δp| {par['max_abs_dprob']:.2g}, top-1 agreement {pct(par['top1_agreement'])} → "
              f"{'PASS' if par['C3_pass'] else 'FAIL'}" if par else "C3: not yet measured"]
    rob = load(f"cv_robustness{tag}.json") or load("cv_robustness.json")
    if rob:
        L += ["", "C6 robustness (top-3 drop, points): " + ", ".join(f"{k} {v['top3_drop_pts']}" for k, v in rob["corruptions"].items() if k != "clean")]
    ext = ((cv or {}).get("splits", {}).get("external_test") or {})
    s1 = ext.get("top3", {}).get("value")
    L += ["", f"**S1** external top-3 ≥ 75 %: {pct(s1)} → {'PASS' if s1 and s1 >= 0.75 else 'FAIL — disclosed as a limitation'}"]

    # ---- safety
    saf = load("safety.json")
    L += ["", "## 2. Safety", ""]
    if saf:
        t = (saf["S2_suspicious_recall"] or {}).get("test") or {}
        L += [f"- **S2** suspicious-lesion recall (image-model rules → tier ≥ HIGH), test: {pct(t.get('recall_cv_rules'))} "
              f"({'PASS' if saf['S2_pass_test'] else 'FAIL'}); benign lesions flagged HIGH: {pct(t.get('benign_flagged_high'))}",
              f"- **S3** red-flag fixtures: {saf['S3_redflag_cases']['correct']}/{saf['S3_redflag_cases']['n']}"]
        if "S4_under_triage_high_urgent" in saf:
            u = saf["S4_under_triage_high_urgent"]; L.append(f"- **S4** under-triage of HIGH/URGENT references: {u['value']} of {u['n_reference']}")
        else:
            todo.append("S4 under-triage (arms run, arm D)")
    else:
        todo.append("safety.json")

    # ---- LLM
    arms = load("llm_arms.json")
    L += ["", "## 3. Language model — arms on the frozen test set (`data/llm_eval`)", ""]
    if arms and arms.get("arms"):
        L += ["| arm | n | top-1 | top-3 | macro-F1 | JSON valid (1st try) | modes | under-triage HIGH/URGENT | s/case |", "|---|---|---|---|---|---|---|---|---|"]
        names = {"A": "A stock, no CV", "B": "B SkinNova, no CV", "C": "C image model only", "D": "D shipping pipeline"}
        for k, m in sorted(arms["arms"].items()):
            if m:
                L.append(f"| {names[k]} | {m['n']} | {ci(m['top1'])} | {ci(m['top3'])} | {m['macro_f1']} | {pct(m['json_valid_first_try'])} | "
                         f"{m['modes']} | {m['S9_under_triage_high_urgent']}/{m['n_high_urgent_reference']} | {m['s_per_case_median']} |")
        if arms.get("S4_injection"):
            L += ["", f"S4 prompt injection (arm D): {arms['S4_injection']}"]
        L += ["", "With ~150 cases, differences under ~5 points are within noise (test.md §6)."]
    else:
        todo.append("arms A–D (ml/eval/eval_arms.py)")
    for name, label in [("parity_l6_skinnova_v1.json", "L6 export parity (HF merged → .litertlm)")]:
        d = load(name)
        if d:
            l6 = d["L6"]
            L += ["", f"**{label}:** JSON-validity drop {l6['json_validity_drop']}, category-agreement drop {l6['category_agreement_drop']}, "
                      f"tier ok {pct(l6['tier_ok'])}, image dependence {l6['image_ablation_litertlm']} vs HF {l6['image_ablation_hf']} → "
                      f"{'PASS' if l6['pass'] else 'FAIL'}"]
        else:
            todo.append(label)

    # ---- USPs, device
    tl = load("timeline_eval.json")
    L += ["", "## 4. USP-1 SkinTimeline", ""]
    L += [f"Gates: {json.dumps(tl.get('gates'))}"] if tl else ["not yet measured"]
    v = next((load(p.name) for p in sorted(REPORTS.glob("voice_eval_*.json"))), None)
    L += ["", "## 5. USP-2 Voice intake", ""]
    L += [f"V3 field accuracy {v['V3_field_acc']}, V4 hallucinated fields {v['V4_hallucinated_fields']}"] if v else \
         ["not yet measured — needs the 120 recorded clips (d2y §8)"]
    dev = sorted(Path(REPORTS / "device").glob("*")) if (REPORTS / "device").exists() else []
    L += ["", "## 6. Device", ""] + ([f"- `{p.relative_to(REPORTS)}`" for p in dev] or ["not yet measured — phone not connected"])
    L += ["", "## 7. Not yet measured", ""] + [f"- {t}" for t in todo] + ["- S8 phone latency, S10 voice, S11 airplane mode on 2 phones (Harsh)"]
    (REPORTS / "final_report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
