from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from ml.common.paths import LLM_DATA, REPORTS, git_sha
from ml.eval.bootstrap import bootstrap_ci


def load(name: str):
    p = REPORTS / name
    try:
        return json.loads(p.read_text()) if p.exists() and p.stat().st_size else None
    except json.JSONDecodeError:
        return None


def pct(x, d=1):
    return "—" if x is None else f"{100 * x:.{d}f} %"


def ci(m):
    if not isinstance(m, dict):
        return "—"
    lo, hi = m.get("ci95", [None, None])
    return f"{100 * m['value']:.1f} % ({100 * lo:.1f}–{100 * hi:.1f})" if lo is not None else f"{100 * m['value']:.1f} %"


def rows(path: Path) -> list[dict]:
    if not path.exists():
        return []
    out = []
    for l in path.read_bytes().split(b"\n"):
        try:
            out.append(json.loads(l))
        except json.JSONDecodeError:
            pass
    return out


def lora_vs_base_real_q():
    """S6: true class listed (category agreement) for arm A (stock) vs arm B (LoRA), both without image-model scores,
    on the frozen llm_test records whose questionnaire answers are real (PAD-UFES / SkinDisNet / SCIN)."""
    meta = {json.loads(l)["id"]: json.loads(l)["meta"] for l in open(LLM_DATA.parent / "llm_eval" / "llm_test.jsonl")}
    res = {}
    for arm in "AB":
        r = [x for x in rows(REPORTS / "arms" / f"{arm}.jsonl") if x["task"] == "T1" and meta.get(x["id"], {}).get("real_q")]
        if not r:
            return None
        res[arm] = bootstrap_ci(lambda t: t.mean(), np.array([float(x["top3"]) for x in r]))
    lo_b, hi_a = res["B"]["ci95"][0], res["A"]["ci95"][1]
    res["non_overlapping"] = lo_b > hi_a
    return res


