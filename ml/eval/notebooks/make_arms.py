"""Kaggle CPU notebook: LLM arms evaluation (ml/eval/eval_arms.py) on llm_test, for the arm that does not need the
fine-tuned model (A = Google's official stock .litertlm without image-model scores) on the frozen llm_eval set. Runs while the
PC trains; results are merged into reports/arms/ locally, where arms B and D run on the SkinNova model.

  python -m ml.eval.notebooks.make_arms push        # needs the dataset version that ships ml/eval/eval_arms.py
  python -m ml.eval.notebooks.make_arms fetch       # → reports/arms/A.jsonl, C.jsonl (+ reports/kaggle/arms/)
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess

from ml.common.paths import REPO, REPORTS
from ml.llm.notebooks.make_kaggle import DATASET, KAGGLE, OWNER

KERNEL = f"{OWNER}/skinnova-arms-eval"
BUILD = REPO / "ml/eval/notebooks/build"
STOCK_REV = "b3ca0d2f076785a8f4b2219ddbd2bdb99954eae1"
N = 150

RUN = f'''
import glob, os, subprocess, sys
data = os.path.dirname(glob.glob("/kaggle/input/**/llm_test.jsonl", recursive=True)[0])
os.makedirs("/tmp/d", exist_ok=True)
if not os.path.exists("/tmp/d/llm"): os.symlink(data, "/tmp/d/llm")          # ml.common.paths: LLM_DATA = DATA/llm
subprocess.run(["rm", "-rf", "/kaggle/working/code"]); subprocess.run(["cp", "-r", data + "/code", "/kaggle/working/code"])
from huggingface_hub import hf_hub_download
stock = hf_hub_download("litert-community/gemma-4-E2B-it-litert-lm", "gemma-4-E2B-it.litertlm", revision="{STOCK_REV}", local_dir="/tmp/ref")
env = dict(os.environ, SKINNOVA_DATA_DIR="/tmp/d", PYTHONPATH="/kaggle/working/code")
p = subprocess.Popen(["/tmp/ve/bin/python", "-m", "ml.eval.eval_arms", "--stock", stock, "--arms", "A", "--n", "{N}", "--threads", "4",
                      "--test-dir", data + "/llm_eval"],
                     cwd="/kaggle/working/code", env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
for line in p.stdout:
    if not line.startswith(("INFO", "WARNING", "W0000", "I0000", "E0000")): print(line, end="")
rc = p.wait(); print("exit code", rc)
subprocess.run(["cp", "-r", "/kaggle/working/code/reports", "/kaggle/working/"])
assert rc == 0
'''


def notebook() -> dict:
    cells = [
        "# SkinNova — arms A (stock) + C (image model only) on llm_test (generated by ml/eval/notebooks/make_arms.py)",
        "%%capture\n!pip install -q uv\n!uv venv /tmp/ve --python 3.12\n"
        '!uv pip install --python /tmp/ve/bin/python "litert-lm-api==0.17.1" "numpy==2.5.2" "pillow==12.3.0" scikit-learn pydantic python-dotenv '
        '"huggingface-hub==1.33.0"',
        RUN.strip(),
    ]
    return {"cells": [{"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": [l + "\n" for l in c.split("\n")]}
                      for c in cells],
            "metadata": {"kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"}}, "nbformat": 4, "nbformat_minor": 5}


def push():
    d = BUILD / "arms"
    shutil.rmtree(d, ignore_errors=True); d.mkdir(parents=True)
    (d / "arms.ipynb").write_text(json.dumps(notebook(), indent=1))
    meta = {"id": KERNEL, "title": "skinnova-arms-eval", "code_file": "arms.ipynb", "language": "python", "kernel_type": "notebook",
            "is_private": True, "enable_gpu": False, "enable_tpu": False, "enable_internet": True,
            "dataset_sources": [DATASET], "competition_sources": [], "kernel_sources": [], "model_sources": []}
    (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    subprocess.run([KAGGLE, "kernels", "push", "-p", str(d)], check=True)


def fetch():
    out = REPORTS / "kaggle/arms"; shutil.rmtree(out, ignore_errors=True); out.mkdir(parents=True)
    subprocess.run([KAGGLE, "kernels", "output", KERNEL, "-p", str(out), "--file-pattern", r".*\.(json|jsonl|log)$"], check=True,
                   stdout=subprocess.DEVNULL)
    (REPORTS / "arms").mkdir(exist_ok=True)
    for arm in ("A",):
        src = out / "reports/arms" / f"{arm}.jsonl"
        if src.exists():
            shutil.copyfile(src, REPORTS / "arms" / f"{arm}.jsonl"); print("copied", arm, sum(1 for _ in open(src)), "rows")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("what", choices=["push", "fetch"])
    push() if ap.parse_args().what == "push" else fetch()
